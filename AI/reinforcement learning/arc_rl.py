# LiDAR Observation Wrapper
# ============================================================
class LiDARWrapper(gym.ObservationWrapper):
    """Replaces image observation with LiDAR rays + car state vector.

    Observation format (48 dims):
        [0:45]  — LiDAR ray distances, normalized to [0, 1] by LIDAR_MAX_RANGE
        [45]    — Forward speed, normalized by MAX_SPEED
        [46]    — Lateral speed, normalized by MAX_SPEED
        [47]    — Angular velocity, normalized (clipped to [-1, 1])
    """

    def __init__(self, env, noise_std=0.0):
        super().__init__(env)
        self.noise_std = noise_std
        self.left_segs = None
        self.right_segs = None

        # New observation space: 45 lidar + 3 car state = 48
        self.observation_space = gym.spaces.Box(
            low=0.0, high=1.0, shape=(LIDAR_NUM_RAYS + 3,), dtype=np.float32
        )

    def reset(self, **kwargs):
        obs, info = self.env.reset(**kwargs)
        # Compute track boundaries for this episode's track
        track = self.unwrapped.track
        self.left_segs, self.right_segs = compute_track_boundaries(track)
        return self.observation(obs), info

    def observation(self, obs):
        car = self.unwrapped.car
        if car is None:
            return np.zeros(LIDAR_NUM_RAYS + 3, dtype=np.float32)

        # Car state
        pos = np.array([car.hull.position[0], car.hull.position[1]])
        angle = car.hull.angle
        vel = car.hull.linearVelocity
        ang_vel = car.hull.angularVelocity

        # Decompose velocity into forward/lateral relative to car heading
        forward_dir = np.array([math.cos(angle), math.sin(angle)])
        lateral_dir = np.array([-math.sin(angle), math.cos(angle)])
        vel_vec = np.array([vel[0], vel[1]])
        forward_speed = np.dot(vel_vec, forward_dir)
        lateral_speed = np.dot(vel_vec, lateral_dir)

        # Cast LiDAR rays
        distances = cast_lidar_rays(pos, angle, self.left_segs, self.right_segs)

        # Add noise for domain randomization (training only)
        if self.noise_std > 0:
            noise = np.random.normal(0, self.noise_std * LIDAR_MAX_RANGE, size=distances.shape)
            distances = np.clip(distances + noise, 0, LIDAR_MAX_RANGE)

        # Normalize everything to [0, 1]
        lidar_norm = distances / LIDAR_MAX_RANGE
        forward_norm = np.clip(forward_speed / MAX_SPEED, -1.0, 1.0) * 0.5 + 0.5
        lateral_norm = np.clip(lateral_speed / MAX_SPEED, -1.0, 1.0) * 0.5 + 0.5
        angvel_norm = np.clip(ang_vel / 5.0, -1.0, 1.0) * 0.5 + 0.5

        observation = np.concatenate([
            lidar_norm,
            [forward_norm, lateral_norm, angvel_norm]
        ]).astype(np.float32)

        return observation


