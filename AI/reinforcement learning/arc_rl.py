# ============================================================
# LiDAR Constants & Core Raycasting Math
# ============================================================
# Real sensor: 720 beams, 360°. We use front 90° (180 beams) downsampled to 45 rays.
LIDAR_NUM_RAYS = 45
LIDAR_FOV = np.pi / 2        # 90° forward arc
LIDAR_MAX_RANGE = 50.0        # Max range in Box2D world units
TRACK_WIDTH = 40.0 / 6.0      # From CarRacing source: TRACK_WIDTH = 40/SCALE, SCALE=6.0

# Precompute ray angles relative to car heading (centered on 0 = straight ahead)
LIDAR_ANGLES = np.linspace(-LIDAR_FOV / 2, LIDAR_FOV / 2, LIDAR_NUM_RAYS)

# Speed normalization constant (approximate max speed in CarRacing)
MAX_SPEED = 50.0


def compute_track_boundaries(track):
    """Convert track centerline into left/right boundary line segments.

    Args:
        track: list of (alpha, beta, x, y) tuples from env.unwrapped.track

    Returns:
        left_segs:  (N, 2, 2) array — each row is [[x1,y1], [x2,y2]]
        right_segs: (N, 2, 2) array
    """
    n = len(track)
    left_points = np.zeros((n, 2))
    right_points = np.zeros((n, 2))

    for i, (alpha, beta, cx, cy) in enumerate(track):
        # Offset perpendicular to track direction (beta is the heading angle)
        dx = TRACK_WIDTH * math.cos(beta + math.pi / 2)
        dy = TRACK_WIDTH * math.sin(beta + math.pi / 2)
        left_points[i] = [cx + dx, cy + dy]
        right_points[i] = [cx - dx, cy - dy]

    # Build segments: connect consecutive points, wrapping around for closed loop
    left_segs = np.stack([left_points, np.roll(left_points, -1, axis=0)], axis=1)
    right_segs = np.stack([right_points, np.roll(right_points, -1, axis=0)], axis=1)

    return left_segs, right_segs


def cast_lidar_rays(car_pos, car_angle, left_segs, right_segs):
    """Cast LiDAR rays and return distances to nearest track boundary.

    Args:
        car_pos:    (2,) array — car world position
        car_angle:  float — car heading in radians
        left_segs:  (N, 2, 2) — left boundary segments
        right_segs: (N, 2, 2) — right boundary segments

    Returns:
        distances: (LIDAR_NUM_RAYS,) array — distance per ray, capped at LIDAR_MAX_RANGE
    """
    # Combine left and right boundary segments
    all_segs = np.concatenate([left_segs, right_segs], axis=0)  # (2N, 2, 2)

    # Prefilter: only test segments within range of the car
    seg_centers = all_segs.mean(axis=1)  # (2N, 2)
    dists_to_car = np.linalg.norm(seg_centers - car_pos, axis=1)
    mask = dists_to_car < (LIDAR_MAX_RANGE + TRACK_WIDTH * 2)
    nearby_segs = all_segs[mask]  # (M, 2, 2)

    if len(nearby_segs) == 0:
        return np.full(LIDAR_NUM_RAYS, LIDAR_MAX_RANGE)

    # Ray directions in world frame
    world_angles = car_angle + LIDAR_ANGLES  # (R,)
    ray_dirs = np.stack([np.cos(world_angles), np.sin(world_angles)], axis=1)  # (R, 2)

    # Segment vectors
    A = nearby_segs[:, 0]  # (M, 2) — segment start points
    B = nearby_segs[:, 1]  # (M, 2) — segment end points
    AB = B - A              # (M, 2)

    # Vectorized ray-segment intersection
    # For each (ray, segment) pair, compute intersection parameters t and s
    P = car_pos  # (2,)
    AP = A - P   # (M, 2)

    # Cross product helper: 2D cross product = a[0]*b[1] - a[1]*b[0]
    # We need: cross(D, AB) for each ray D and each segment AB
    # ray_dirs: (R, 2), AB: (M, 2)
    # Result shapes: (R, M)
    D_cross_AB = ray_dirs[:, 0, None] * AB[None, :, 1] - ray_dirs[:, 1, None] * AB[None, :, 0]
    AP_cross_AB = AP[:, 0] * AB[:, 1] - AP[:, 1] * AB[:, 0]  # (M,)
    AP_cross_D = AP[None, :, 0] * ray_dirs[:, 1, None] - AP[None, :, 1] * ray_dirs[:, 0, None]  # (R, M)

    # Avoid division by zero for parallel rays
    parallel = np.abs(D_cross_AB) < 1e-10
    D_cross_AB_safe = np.where(parallel, 1.0, D_cross_AB)

    t = AP_cross_AB[None, :] / D_cross_AB_safe   # (R, M) — distance along ray
    s = AP_cross_D / D_cross_AB_safe              # (R, M) — position along segment [0,1]

    # Valid hit: t > 0 (forward along ray) and 0 <= s <= 1 (within segment)
    valid = (~parallel) & (t > 1e-6) & (s >= 0) & (s <= 1) & (t <= LIDAR_MAX_RANGE)

    # For each ray, find the minimum t among valid hits
    t_masked = np.where(valid, t, LIDAR_MAX_RANGE)
    distances = t_masked.min(axis=1)  # (R,)

    return distances


