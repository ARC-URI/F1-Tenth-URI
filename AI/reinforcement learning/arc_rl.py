def draw_lidar_on_frame(frame, car_pixel_pos, car_angle, distances):
    """Overlay LiDAR rays on an RGB frame.

    Args:
        frame: (H, W, 3) RGB array
        car_pixel_pos: (x, y) pixel position of car in the frame
        car_angle: car heading in radians
        distances: (45,) raw LiDAR distances
    """
    overlay = frame.copy()
    cx, cy = int(car_pixel_pos[0]), int(car_pixel_pos[1])

    for i, (angle_offset, dist) in enumerate(zip(LIDAR_ANGLES, distances)):
        world_angle = car_angle + angle_offset
        # Scale distance to pixels (approximate: ~6.0 pixels per world unit at default zoom)
        pixel_dist = dist * 6.0
        ex = int(cx + pixel_dist * math.cos(world_angle))
        ey = int(cy - pixel_dist * math.sin(world_angle))  # y is flipped in pixel coords

        # Color: red (close) -> yellow -> green (far)
        ratio = min(dist / LIDAR_MAX_RANGE, 1.0)
        r = int(255 * (1 - ratio))
        g = int(255 * ratio)
        color = (r, g, 0)

        cv2.line(overlay, (cx, cy), (ex, ey), color, 1, cv2.LINE_AA)
        cv2.circle(overlay, (ex, ey), 2, color, -1)

    # Blend overlay
    return cv2.addWeighted(overlay, 0.7, frame, 0.3, 0)


def record_video_with_lidar(model, env_id, max_steps=1000):
    """Record frames with LiDAR rays overlaid."""
    render_env = gym.make(env_id, continuous=True, render_mode="rgb_array")
    lidar_env = LiDARWrapper(render_env, noise_std=0.0)

    obs, _ = lidar_env.reset()
    frames = []

    for _ in range(max_steps):
        # Get RGB frame for display
        rgb_frame = render_env.render()
        if rgb_frame is None:
            break

        # Get car state for overlay
        car = render_env.unwrapped.car
        if car is not None:
            pos = np.array([car.hull.position[0], car.hull.position[1]])
            angle = car.hull.angle
            distances = cast_lidar_rays(pos, angle, lidar_env.left_segs, lidar_env.right_segs)

            # Convert car world position to pixel position in the frame
            # CarRacing renders at 96x96 with the car roughly centered
            h, w = rgb_frame.shape[:2]
            car_pixel = (w // 2, int(h * 0.75))  # Car is centered horizontally, ~75% down

            frame_with_lidar = draw_lidar_on_frame(rgb_frame, car_pixel, angle, distances)
            frames.append(frame_with_lidar)
        else:
            frames.append(rgb_frame)

        # Step with the LiDAR observation
        action, _ = model.predict(obs.reshape(1, -1), deterministic=True)
        obs, reward, terminated, truncated, _ = lidar_env.step(action[0])
        if terminated or truncated:
            break

    lidar_env.close()
    return frames


def display_video_mp4(frames, fps=30, filename="car_lidar.mp4"):
    """Save as MP4 and display inline in Colab."""
    h, w = frames[0].shape[:2]
    fourcc = cv2.VideoWriter_fourcc(*"mp4v")
    out = cv2.VideoWriter(filename, fourcc, fps, (w, h))
    for frame in frames:
        out.write(cv2.cvtColor(frame, cv2.COLOR_RGB2BGR))
    out.release()

    # Re-encode with H.264 for browser playback
    subprocess.run(
        ["ffmpeg", "-y", "-i", filename, "-vcodec", "libx264",
         "-f", "mp4", "_playable.mp4", "-loglevel", "quiet"],
        check=True,
    )

    with open("_playable.mp4", "rb") as f:
        mp4_data = base64.b64encode(f.read()).decode()
    display(HTML(f"""
        <video width="480" controls autoplay loop>
            <source src="data:video/mp4;base64,{mp4_data}" type="video/mp4">
        </video>
    """))


